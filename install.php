/* ----------------------------- small helpers ----------------------------- */

function esc($s): string { return htmlspecialchars((string) $s, ENT_QUOTES, 'UTF-8'); }
function itoken(): string { return $_SESSION['itoken']; }
function icheck(): void
{
    if (!hash_equals($_SESSION['itoken'] ?? '', $_POST['itoken'] ?? '')) {
        http_response_code(400);
        exit('Your setup session expired. Reload install.php and start again.');
    }
}

function installer_pdo(string $host, string $name, string $user, string $pass): PDO
{
    $dsn = 'mysql:host=' . $host . ';dbname=' . $name . ';charset=utf8mb4';
    return new PDO($dsn, $user, $pass, [
        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]);
}

function build_config(array $v): string
{
    $q = function ($x) { return "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], (string) $x) . "'"; };
    return "<?php\n"
        . "/**\n * MustrHQ — configuration (generated by install.php)\n * You can edit these values by hand at any time.\n */\n\n"
        . "// ---- Database ----\n"
        . "define('DB_HOST', " . $q($v['db_host']) . ");\n"
        . "define('DB_NAME', " . $q($v['db_name']) . ");\n"
        . "define('DB_USER', " . $q($v['db_user']) . ");\n"
        . "define('DB_PASS', " . $q($v['db_pass']) . ");\n\n"
        . "// ---- App settings ----\n"
        . "define('APP_NAME', " . $q($v['app_name']) . ");\n"
        . "define('APP_TZ', " . $q($v['app_tz']) . ");\n"
        . "define('CURRENCY', " . $q($v['currency']) . ");\n\n"
        . "// ---- Attendance rules ----\n"
        . "define('GRACE_MINUTES', 10);        // minutes after expected start before a clock-in is \"late\"\n"
        . "define('NOSHOW_AFTER_MINUTES', 60); // minutes past expected start with no clock-in => \"no-show\"\n\n"
        . "// ---- Kiosk PIN safety ----\n"
        . "define('PIN_MAX_ATTEMPTS', 5);\n"
        . "define('PIN_LOCK_SECONDS', 60);\n\n"
        . "// ---- Kiosk gate (empty = open; a value locks the kiosk to devices that visited with ?key=) ----\n"
        . "define('KIOSK_KEY', " . $q($v['kiosk_key']) . ");\n\n"
        . "// ---- Session cookie name ----\n"
        . "define('SESSION_NAME', 'kclock');\n\n"
        . "define('INSTALLED', true);\n";
}

function run_schema(PDO $pdo): void
{
    $sql = file_get_contents(SCHEMA_FILE);
    if ($sql === false) throw new RuntimeException('Could not read schema.sql — make sure it was uploaded.');

    // Strip comments BEFORE splitting on ';', otherwise a ';' inside a comment
    // (e.g. "-- UTC; NULL = ...") would chop a statement in half.
    // This schema has no ';', '--' or '#' inside string literals, so a plain
    // strip is safe here.
    $sql = preg_replace('#/\*.*?\*/#s', '', $sql);   // /* block */ comments
    $sql = preg_replace('/--[^\r\n]*/', '', $sql);   // -- line comments (anywhere on the line)
    $sql = preg_replace('/#[^\r\n]*/', '', $sql);    // # line comments

    $statements = array_filter(array_map('trim', explode(';', $sql)), function ($s) { return $s !== ''; });
    foreach ($statements as $st) {
        // don't duplicate the starter brands/roles if they already exist
        if (preg_match('/^INSERT\s+INTO\s+brands\b/i', $st)) {
            if ((int) $pdo->query('SELECT COUNT(*) FROM brands')->fetchColumn() > 0) continue;
        } elseif (preg_match('/^INSERT\s+INTO\s+roles\b/i', $st)) {
            if ((int) $pdo->query('SELECT COUNT(*) FROM roles')->fetchColumn() > 0) continue;
        }
        $pdo->exec($st);
    }
}

function create_admin(PDO $pdo, string $user, string $passHash): void
{
    if ((int) $pdo->query('SELECT COUNT(*) FROM admins')->fetchColumn() === 0) {
        $pdo->prepare('INSERT INTO admins (username, password_hash, created_at) VALUES (?,?,?)')
            ->execute([$user, $passHash, gmdate('Y-m-d H:i:s')]);
    }
}

function ensure_htaccess(): void
{
    if (!is_dir(UPLOADS_DIR)) @mkdir(UPLOADS_DIR, 0755, true);
    $h = UPLOADS_DIR . '/.htaccess';
    if (is_dir(UPLOADS_DIR) && !is_file($h)) {
        @file_put_contents($h, "<FilesMatch \"\\.(php|php3|php4|php5|php7|phtml|pht|phar|cgi|pl|py|asp|aspx|sh)$\">\n    Require all denied\n</FilesMatch>\nOptions -ExecCGI -Indexes\n");
    }

    // No directory listings anywhere, and keep sensitive files unreachable.
    $root = __DIR__ . '/.htaccess';
    if (!is_file($root)) {
        @file_put_contents($root,
            "Options -Indexes\n"
            . "DirectoryIndex index.php index.html\n\n"
            . "<FilesMatch \"(^\\.|\\.(sql|zip|tar|gz|md|log|bak|old|ini|sh)$)\">\n"
            . "    Require all denied\n"
            . "    <IfModule !mod_authz_core.c>\n        Order allow,deny\n        Deny from all\n    </IfModule>\n"
            . "</FilesMatch>\n\n"
            . "<Files \"config.php\">\n    Require all denied\n"
            . "    <IfModule !mod_authz_core.c>\n        Order allow,deny\n        Deny from all\n    </IfModule>\n</Files>\n");
    }

    // Backups may contain source code — never serve them.
    $bdir = __DIR__ . '/backups';
    if (!is_dir($bdir)) @mkdir($bdir, 0755, true);
    $bh = $bdir . '/.htaccess';
    if (is_dir($bdir) && !is_file($bh)) {
        @file_put_contents($bh, "Require all denied\n<IfModule !mod_authz_core.c>\n    Order allow,deny\n    Deny from all\n</IfModule>\n");
    }
}

