/* -------------------------------- routing -------------------------------- */

$step = $_POST['step'] ?? $_GET['step'] ?? 'welcome';

// success page first, so the post-install redirect always lands here
if ($step === 'done') {
    if (empty($_SESSION['install_complete'])) { header('Location: install.php'); exit; }
    render_done();
    exit;
}

// already installed? (real DB in config + an admin row)
$alreadyInstalled = false;
if (defined('DB_NAME') && DB_NAME !== 'your_db_name') {
    try {
        $probe = installer_pdo(DB_HOST, DB_NAME, DB_USER, DB_PASS);
        if ((int) $probe->query('SELECT COUNT(*) FROM admins')->fetchColumn() > 0) {
            $alreadyInstalled = true;
        }
    } catch (Throwable $e) { /* not actually installed */ }
}
if ($alreadyInstalled) { render_locked(); exit; }

if ($step === 'run' && $_SERVER['REQUEST_METHOD'] === 'POST') {
    icheck();

    $v = [
        'db_host'   => trim($_POST['db_host'] ?? ''),
        'db_name'   => trim($_POST['db_name'] ?? ''),
        'db_user'   => trim($_POST['db_user'] ?? ''),
        'db_pass'   => (string) ($_POST['db_pass'] ?? ''),
        'app_name'  => trim($_POST['app_name'] ?? 'MustrHQ'),
        'app_tz'    => trim($_POST['app_tz'] ?? 'Europe/London'),
        'currency'  => trim($_POST['currency'] ?? '£'),
        'admin_user' => trim($_POST['admin_user'] ?? ''),
        'admin_pass' => (string) ($_POST['admin_pass'] ?? ''),
        'admin_pass2' => (string) ($_POST['admin_pass2'] ?? ''),
        'kiosk_lock' => !empty($_POST['kiosk_lock']) ? '1' : '',
    ];
    // keep a previously generated kiosk key across the manual-config round trip
    if (isset($_POST['kiosk_key']) && $_POST['kiosk_key'] !== '') {
        $v['kiosk_key'] = (string) $_POST['kiosk_key'];
    } else {
        $v['kiosk_key'] = $v['kiosk_lock'] ? bin2hex(random_bytes(16)) : '';
    }

    $errors = [];
    if ($v['db_host'] === '' || $v['db_name'] === '' || $v['db_user'] === '') $errors[] = 'Fill in the database host, name and user.';
    if ($v['app_name'] === '') $errors[] = 'Enter an app name.';
    if ($v['currency'] === '') $errors[] = 'Enter a currency symbol.';
    if (!in_array($v['app_tz'], DateTimeZone::listIdentifiers(), true)) $errors[] = 'Choose a valid timezone.';
    if ($v['admin_user'] === '' || mb_strlen($v['admin_user']) > 60) $errors[] = 'Enter an admin username (up to 60 characters).';
    if (strlen($v['admin_pass']) < 8) $errors[] = 'Use an admin password of at least 8 characters.';
    if ($v['admin_pass'] !== $v['admin_pass2']) $errors[] = 'The admin passwords do not match.';

    $pdo = null;
    if (!$errors) {
        try {
            $pdo = installer_pdo($v['db_host'], $v['db_name'], $v['db_user'], $v['db_pass']);
        } catch (Throwable $e) {
            $errors[] = 'Could not connect to the database: ' . $e->getMessage();
            $errors[] = 'Check the details, and make sure the database exists and the user has access to it (both are created in cPanel → MySQL Databases).';
        }
    }
    if ($errors) { render_form($v, $errors); exit; }

    // write config.php (or fall back to manual creation)
    if (empty($_POST['config_written'])) {
        $written = @file_put_contents(CONFIG_FILE, build_config($v), LOCK_EX);
        if ($written === false) { render_manual_config($v, build_config($v)); exit; }
    }

    try {
        run_schema($pdo);
        create_admin($pdo, $v['admin_user'], password_hash($v['admin_pass'], PASSWORD_DEFAULT));
        ensure_htaccess();
    } catch (Throwable $e) {
        render_form($v, ['The database step failed: ' . $e->getMessage()]);
        exit;
    }

    $_SESSION['done_kiosk_key'] = $v['kiosk_key'];
    $_SESSION['install_complete'] = true;
    header('Location: install.php?step=done');
    exit;
}

if ($step === 'config') {
    render_form([
        'db_host' => 'localhost', 'db_name' => '', 'db_user' => '', 'db_pass' => '',
        'app_name' => 'MustrHQ', 'app_tz' => 'Europe/London', 'currency' => '£',
        'admin_user' => '', 'admin_pass' => '', 'admin_pass2' => '', 'kiosk_lock' => '', 'kiosk_key' => '',
    ], []);
    exit;
}

