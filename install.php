    ['label' => 'PHP 7.4 or newer', 'ok' => version_compare(PHP_VERSION, '7.4.0', '>='), 'hard' => true, 'detail' => 'You have PHP ' . PHP_VERSION],
    ['label' => 'MySQL support (pdo_mysql)', 'ok' => extension_loaded('pdo_mysql'), 'hard' => true, 'detail' => ''],
    ['label' => 'Multibyte strings (mbstring)', 'ok' => extension_loaded('mbstring'), 'hard' => true, 'detail' => ''],
    ['label' => 'JSON support', 'ok' => function_exists('json_encode'), 'hard' => true, 'detail' => ''],
    ['label' => 'Image detection (fileinfo)', 'ok' => extension_loaded('fileinfo'), 'hard' => false, 'detail' => 'Needed only for staff photo uploads'],
    ['label' => 'config.php is writable', 'ok' => is_file(CONFIG_FILE) && is_writable(CONFIG_FILE), 'hard' => false, 'detail' => "If not, you'll be shown the file to create by hand"],
    ['label' => 'uploads/ is writable', 'ok' => is_dir(UPLOADS_DIR) && is_writable(UPLOADS_DIR), 'hard' => false, 'detail' => 'Needed only for staff photo uploads'],
];
$hardFail = false;
foreach ($reqs as $r) { if ($r['hard'] && !$r['ok']) $hardFail = true; }
render_welcome($reqs, $hardFail);
